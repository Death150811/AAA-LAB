CREATE TABLE employees (
  id         integer PRIMARY KEY,
  name       text    NOT NULL,
  dept       text    NOT NULL,
  salary     integer NOT NULL CHECK (salary > 0),
  manager_id integer REFERENCES employees (id),
  hired_on   date    NOT NULL
);

