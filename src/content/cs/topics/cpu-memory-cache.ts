// Модель, а не измерение реального CPU: считаем выполненные инструкции и обращения к памяти.
function run(program, memory, { trace = 0 } = {}) {
  const reg = [0, 0, 0, 0];           // регистры r0..r3
  let pc = 0;                         // счётчик команд
  const stat = { instr: 0, loads: 0, stores: 0, branches: 0, taken: 0 };
  while (true) {
    const [op, a, b] = program[pc];   // выборка и декодирование
    if (trace && stat.instr < trace) console.log(String(pc).padStart(2), op.padEnd(5), String(a ?? "").padEnd(3), String(b ?? "").padEnd(4), "  регистры:", reg.join(" "));
    stat.instr++;
    pc++;                             // по умолчанию — следующая команда
    switch (op) {                     // исполнение
      case "LI":   reg[a] = b; break;                         // r[a] = константа
      case "ADD":  reg[a] += reg[b]; break;                   // r[a] += r[b]
      case "SUB1": reg[a] -= 1; break;                        // r[a] -= 1
      case "LD":   reg[a] = memory[b]; stat.loads++; break;   // r[a] = память[b]
      case "ST":   memory[b] = reg[a]; stat.stores++; break;  // память[b] = r[a]
      case "JNZ":  stat.branches++; if (reg[a] !== 0) { pc = b; stat.taken++; } break;
      case "HALT": return { reg, stat };
    }
  }
}

