          // Оценка сдвига по определению CLS: доля затронутой области × доля расстояния
          function layoutShiftScore(change) {
            const before = tracked.map((el) => el.getBoundingClientRect());
            change();
            const after = tracked.map((el) => el.getBoundingClientRect());

            const vw = innerWidth, vh = innerHeight;
            const spans = [];
            let maxMove = 0;
            tracked.forEach((_, i) => {
              const move = Math.max(Math.abs(after[i].top - before[i].top), Math.abs(after[i].left - before[i].left));
              if (move > 0.5) {
                maxMove = Math.max(maxMove, move);
                spans.push([before[i].top, before[i].bottom], [after[i].top, after[i].bottom]);
              }
            });
            spans.sort((a, b) => a[0] - b[0]);
            let area = 0, cur = null;
            for (const [t, b] of spans) {
              const s = Math.max(0, t), e = Math.min(vh, b);
              if (e <= s) continue;
              if (!cur || s > cur[1]) { if (cur) area += cur[1] - cur[0]; cur = [s, e]; }
              else cur[1] = Math.max(cur[1], e);
            }
            if (cur) area += cur[1] - cur[0];
            return ((area * vw) / (vw * vh)) * (maxMove / Math.max(vw, vh));
          }

